func GenerateRandomPlate() string {
	letters := "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
	digits := "0123456789"

	plate := ""
	for i := 0; i < 2; i++ {
		plate += string(letters[rand.Intn(len(letters))])
	}
	plate += "-"
	for i := 0; i < 3; i++ {
		plate += string(digits[rand.Intn(len(digits))])
	}
	plate += "-"
	plate += string(letters[rand.Intn(len(letters))])

	return plate
}
